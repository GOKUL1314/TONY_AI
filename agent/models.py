"""
Data Models for TONY AI Agent Subsystem (Stage 10).
Defines structured classes for agent plans, steps, observations, states, failures, and tasks.
"""
from dataclasses import dataclass, field, asdict
from datetime import datetime
from enum import Enum
from typing import Dict, Any, List, Optional
import uuid


class AgentStepStatus(str, Enum):
    """Lifecycle statuses for an individual agent step."""
    PENDING = "pending"
    READY = "ready"
    RUNNING = "running"
    WAITING_CONFIRMATION = "waiting_confirmation"
    COMPLETED = "completed"
    FAILED = "failed"
    SKIPPED = "skipped"
    CANCELLED = "cancelled"
    BLOCKED = "blocked"
    PAUSED = "paused"


class AgentTaskStatus(str, Enum):
    """Lifecycle statuses for an overarching agent task."""
    QUEUED = "queued"
    PLANNING = "planning"
    RUNNING = "running"
    PAUSED = "paused"
    WAITING_CONFIRMATION = "waiting_confirmation"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"


class AgentRiskLevel(str, Enum):
    """Security risk assessment levels for actions."""
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


@dataclass
class AgentObservation:
    """Structured perception of an action result observed by the agent."""
    step_id: str
    action_type: str
    status: str
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())
    output: Optional[Any] = None
    error: Optional[str] = None
    detected_entities: Dict[str, Any] = field(default_factory=dict)
    metrics: Dict[str, Any] = field(default_factory=dict)
    notes: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "step_id": self.step_id,
            "action_type": self.action_type,
            "status": self.status,
            "timestamp": self.timestamp,
            "output": self.output,
            "error": self.error,
            "detected_entities": self.detected_entities,
            "metrics": self.metrics,
            "notes": self.notes
        }


@dataclass
class AgentFailure:
    """Diagnostic categorization of a step or task failure."""
    failure_type: str  # transient, invalid_input, missing_dependency, permission_security, provider_unavailable, quota_limit, confirmation_required, unknown
    recoverable: bool = False
    retry_count: int = 0
    max_retries: int = 2
    error_message: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "failure_type": self.failure_type,
            "recoverable": self.recoverable,
            "retry_count": self.retry_count,
            "max_retries": self.max_retries,
            "error_message": self.error_message
        }


@dataclass
class AgentStepResult:
    """Outcome payload generated by step execution."""
    success: bool
    data: Any = None
    error: Optional[str] = None
    duration_seconds: float = 0.0
    untrusted_content: bool = False

    def to_dict(self) -> Dict[str, Any]:
        out_data = self.data
        if hasattr(out_data, "to_dict"):
            out_data = out_data.to_dict()
        return {
            "success": self.success,
            "data": out_data,
            "error": self.error,
            "duration_seconds": round(self.duration_seconds, 3),
            "untrusted_content": self.untrusted_content
        }


@dataclass
class AgentStep:
    """A single atomic, dependency-aware action unit in an AgentPlan."""
    step_id: str
    description: str
    action_type: str
    intent: Optional[str] = None
    arguments: Dict[str, Any] = field(default_factory=dict)
    dependencies: List[str] = field(default_factory=list)
    status: AgentStepStatus = AgentStepStatus.PENDING
    result: Optional[Any] = None
    error: Optional[str] = None
    retry_count: int = 0
    max_retries: int = 2
    requires_confirmation: bool = False
    risk_level: AgentRiskLevel = AgentRiskLevel.LOW
    started_at: Optional[str] = None
    completed_at: Optional[str] = None
    observation: Optional[AgentObservation] = None
    failure: Optional[AgentFailure] = None

    def to_dict(self) -> Dict[str, Any]:
        res_data = self.result
        if hasattr(res_data, "to_dict"):
            res_data = res_data.to_dict()
        return {
            "step_id": self.step_id,
            "description": self.description,
            "action_type": self.action_type,
            "intent": self.intent,
            "arguments": self.arguments,
            "dependencies": self.dependencies,
            "status": self.status.value if isinstance(self.status, AgentStepStatus) else str(self.status),
            "result": res_data,
            "error": self.error,
            "retry_count": self.retry_count,
            "max_retries": self.max_retries,
            "requires_confirmation": self.requires_confirmation,
            "risk_level": self.risk_level.value if isinstance(self.risk_level, AgentRiskLevel) else str(self.risk_level),
            "started_at": self.started_at,
            "completed_at": self.completed_at,
            "observation": self.observation.to_dict() if self.observation else None,
            "failure": self.failure.to_dict() if self.failure else None
        }


@dataclass
class AgentPlan:
    """A structured DAG-like multi-step execution plan."""
    plan_id: str
    user_goal: str
    steps: List[AgentStep] = field(default_factory=list)
    status: AgentTaskStatus = AgentTaskStatus.QUEUED
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())
    completed_at: Optional[str] = None
    current_step_index: int = 0

    @property
    def progress_percent(self) -> int:
        if not self.steps:
            return 100 if self.status == AgentTaskStatus.COMPLETED else 0
        completed = sum(1 for s in self.steps if s.status in (AgentStepStatus.COMPLETED, AgentStepStatus.SKIPPED))
        return int((completed / len(self.steps)) * 100)

    def get_ready_steps(self) -> List[AgentStep]:
        """Find steps whose dependencies are all satisfied and are ready to run."""
        completed_ids = {s.step_id for s in self.steps if s.status == AgentStepStatus.COMPLETED}
        ready = []
        for s in self.steps:
            if s.status == AgentStepStatus.PENDING:
                if all(dep in completed_ids for dep in s.dependencies):
                    ready.append(s)
        return ready

    def to_dict(self) -> Dict[str, Any]:
        return {
            "plan_id": self.plan_id,
            "user_goal": self.user_goal,
            "status": self.status.value if isinstance(self.status, AgentTaskStatus) else str(self.status),
            "created_at": self.created_at,
            "completed_at": self.completed_at,
            "current_step_index": self.current_step_index,
            "progress_percent": self.progress_percent,
            "steps": [s.to_dict() for s in self.steps]
        }


@dataclass
class AgentTask:
    """Top-level agent task managing plan lifecycle, session context, and user feedback."""
    task_id: str
    user_goal: str
    plan: AgentPlan
    conversation_id: str = "default_session"
    status: AgentTaskStatus = AgentTaskStatus.QUEUED
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())
    natural_response: Optional[str] = None
    error: Optional[str] = None
    result: Optional[Any] = None
    pending_confirmation_id: Optional[str] = None
    is_paused: bool = False
    is_cancelled: bool = False

    def to_dict(self) -> Dict[str, Any]:
        res_data = self.result
        if hasattr(res_data, "to_dict"):
            res_data = res_data.to_dict()
        return {
            "task_id": self.task_id,
            "conversation_id": self.conversation_id,
            "user_goal": self.user_goal,
            "status": self.status.value if isinstance(self.status, AgentTaskStatus) else str(self.status),
            "created_at": self.created_at,
            "natural_response": self.natural_response,
            "error": self.error,
            "result": res_data,
            "pending_confirmation_id": self.pending_confirmation_id,
            "is_paused": self.is_paused,
            "is_cancelled": self.is_cancelled,
            "plan": self.plan.to_dict()
        }
