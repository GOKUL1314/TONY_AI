"""
Conversation memory and persistence service for TONY.
Provides basic local storage for session history, designed to be swapped
for a vector database or long-term memory system in Stage 4.
"""
from datetime import datetime
import json
import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger("tony.services.conversation")


class ConversationService:
    """
    Manages local storage and retrieval of conversation turns.
    Stores timestamp, user message, and TONY response in JSON format.
    """

    def __init__(self, storage_dir: Path):
        self.storage_dir = Path(storage_dir)
        self.storage_dir.mkdir(parents=True, exist_ok=True)
        self.session_file = self.storage_dir / "active_session.json"
        self._ensure_storage_file()

    def _ensure_storage_file(self) -> None:
        """Create initial session JSON file if not present."""
        if not self.session_file.exists():
            initial_data = {
                "session_id": "default",
                "created_at": datetime.now().isoformat(),
                "updated_at": datetime.now().isoformat(),
                "turns": []
            }
            self._write_file(initial_data)

    def _read_file(self) -> dict[str, Any]:
        """Safely read session data from disk."""
        try:
            with open(self.session_file, "r", encoding="utf-8") as f:
                return json.load(f)
        except (json.JSONDecodeError, FileNotFoundError) as e:
            logger.warning(f"Error reading conversation file ({e}). Re-initializing.")
            fresh_data = {
                "session_id": "default",
                "created_at": datetime.now().isoformat(),
                "updated_at": datetime.now().isoformat(),
                "turns": []
            }
            self._write_file(fresh_data)
            return fresh_data

    def _write_file(self, data: dict[str, Any]) -> None:
        """Write session data to disk atomically."""
        temp_file = self.session_file.with_suffix(".tmp")
        with open(temp_file, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
        temp_file.replace(self.session_file)

    def add_turn(self, user_message: str, assistant_response: str) -> dict[str, Any]:
        """
        Record a single dialogue turn to storage.

        :param user_message: The message typed by the user.
        :param assistant_response: The answer generated by TONY.
        :return: The stored turn entry.
        """
        data = self._read_file()
        timestamp = datetime.now().isoformat()
        turn_id = len(data.get("turns", [])) + 1

        entry = {
            "id": turn_id,
            "timestamp": timestamp,
            "user_message": user_message,
            "assistant_response": assistant_response
        }

        data.setdefault("turns", []).append(entry)
        data["updated_at"] = timestamp
        self._write_file(data)
        logger.debug(f"Saved turn #{turn_id} to conversation history.")
        return entry

    def get_history(self, limit: int = 50) -> list[dict[str, Any]]:
        """
        Retrieve recent conversation turns.

        :param limit: Maximum number of recent turns to return.
        :return: List of turn dictionaries.
        """
        data = self._read_file()
        turns = data.get("turns", [])
        return turns[-limit:] if limit > 0 else turns

    def get_provider_context(self, limit: int = 10) -> list[dict[str, str]]:
        """
        Format recent turns into standard LLM role/message format for context injection.

        :param limit: Number of recent turns to include.
        :return: List of turns: [{'role': 'user', 'message': '...'}, {'role': 'assistant', 'message': '...'}]
        """
        history = self.get_history(limit=limit)
        context: list[dict[str, str]] = []
        for turn in history:
            context.append({"role": "user", "message": turn.get("user_message", "")})
            context.append({"role": "assistant", "message": turn.get("assistant_response", "")})
        return context

    def get_compacted_provider_context(
        self,
        limit: int = 20,
        max_chars: int = 2500,
        keep_recent_turns: int = 2
    ) -> list[dict[str, str]]:
        """
        Format turns into token-budgeted, compacted context using ContextCompactor.
        Preserves recent turns verbatim and summarizes older turns into a dense recap block.
        """
        history = self.get_history(limit=limit)
        from intelligence.context_compactor import ContextCompactor
        return ContextCompactor.compact_history(
            history,
            max_chars=max_chars,
            keep_recent_turns=keep_recent_turns
        )

    def clear_history(self) -> None:
        """Clear active conversation history."""
        # Archive current session if it contains turns
        data = self._read_file()
        turns = data.get("turns", [])
        if turns:
            timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")
            archive_file = self.storage_dir / f"session_archive_{timestamp_str}.json"
            try:
                with open(archive_file, "w", encoding="utf-8") as f:
                    json.dump(data, f, indent=2, ensure_ascii=False)
                logger.info(f"Archived previous session to {archive_file.name}")
            except Exception as e:
                logger.warning(f"Could not archive session: {e}")

        fresh_data = {
            "session_id": "default",
            "created_at": datetime.now().isoformat(),
            "updated_at": datetime.now().isoformat(),
            "turns": []
        }
        self._write_file(fresh_data)
        logger.info("Cleared active conversation history.")
