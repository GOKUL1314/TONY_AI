"""
Local LLM Provider adapter for Ollama.
Communicates with a locally running Ollama instance via its REST API.
"""
import logging
from typing import Any, Optional
import requests
from ai.provider import AIProvider, AIProviderError

logger = logging.getLogger("tony.ai.local")


class LocalProvider(AIProvider):
    """
    Adapter for local LLM inference engines, specifically Ollama.
    Allows TONY to operate completely offline without external APIs.
    """

    def __init__(
        self,
        model_name: str = "llama3.2:1b",
        base_url: str = "http://localhost:11434",
        timeout: int = 60,
        system_prompt: str = "",
        num_ctx: Optional[int] = None,
        temperature: Optional[float] = None,
        num_predict: Optional[int] = None,
        top_p: Optional[float] = None
    ):
        super().__init__(model_name=model_name)
        self.base_url = base_url.rstrip("/")
        import os
        self.timeout = timeout if timeout is not None else int(os.getenv("OLLAMA_TIMEOUT", "120"))
        self.system_prompt = system_prompt
        self.provider_name = "local (Ollama)"

        # Antigravity fast inference tuning (prevents memory paging, caps output length)
        self.num_ctx = num_ctx or int(os.getenv("OLLAMA_NUM_CTX", "4096"))
        self.temperature = temperature if temperature is not None else float(os.getenv("OLLAMA_TEMPERATURE", "0.3"))
        self.num_predict = num_predict or int(os.getenv("OLLAMA_NUM_PREDICT", "600"))
        self.top_p = top_p if top_p is not None else float(os.getenv("OLLAMA_TOP_P", "0.9"))

    def _build_messages(self, message: str, history: list[dict[str, str]] | None) -> list[dict[str, str]]:
        """Format conversation turns for Ollama chat API."""
        messages: list[dict[str, str]] = []

        if self.system_prompt:
            messages.append({"role": "system", "content": self.system_prompt})

        if history:
            for turn in history:
                role = turn.get("role", "user")
                content = turn.get("message", "")
                if content:
                    messages.append({"role": role, "content": content})

        messages.append({"role": "user", "content": message})
        return messages

    def generate_response(self, message: str, history: list[dict[str, str]] | None = None) -> str:
        """
        Send chat prompt and history to Ollama /api/chat.

        :param message: Current user message.
        :param history: Prior conversation turns.
        :return: Response text generated by the local model.
        """
        endpoint = f"{self.base_url}/api/chat"
        import time
        messages = self._build_messages(message, history)
        msg_count = len(messages)
        prompt_chars = sum(len(m.get("content", "")) for m in messages)
        t_start = time.time()

        payload = {
            "model": self.model_name,
            "messages": messages,
            "stream": False,
            "options": {
                "num_ctx": self.num_ctx,
                "temperature": self.temperature,
                "num_predict": self.num_predict,
                "top_p": self.top_p
            }
        }

        try:
            logger.info(
                f"Initiating local inference: model='{self.model_name}', "
                f"messages={msg_count}, prompt_chars={prompt_chars}, timeout={self.timeout}s"
            )
            response = requests.post(endpoint, json=payload, timeout=self.timeout)

            if response.status_code == 404:
                raise AIProviderError(
                    f"Model '{self.model_name}' was not found in your local Ollama library. "
                    f"Please pull the model using `ollama pull {self.model_name}`."
                )

            if response.status_code != 200:
                raise AIProviderError(
                    f"Ollama returned HTTP {response.status_code}: {response.text}"
                )

            data = response.json()
            reply = data.get("message", {}).get("content", "").strip()
            if not reply:
                raise AIProviderError("Received an empty response from local model.")

            elapsed_ms = int((time.time() - t_start) * 1000)
            logger.info(
                f"Local inference completed: model='{self.model_name}', "
                f"response_chars={len(reply)}, elapsed_ms={elapsed_ms}ms"
            )
            return reply

        except requests.exceptions.ConnectionError:
            err_msg = (
                f"Unable to connect to local Ollama server at {self.base_url}. "
                "Please verify that Ollama is installed and running (e.g. `ollama serve`), "
                "or switch to mock/cloud provider in .env."
            )
            logger.error(err_msg)
            raise AIProviderError(err_msg)

        except requests.exceptions.Timeout:
            elapsed_ms = int((time.time() - t_start) * 1000)
            err_msg = (
                f"Local model inference timed out after {self.timeout}s "
                f"[model='{self.model_name}', prompt_chars={prompt_chars}, elapsed={elapsed_ms}ms]."
            )
            logger.error(err_msg)
            raise AIProviderError(err_msg)

        except requests.exceptions.RequestException as e:
            err_msg = f"Network error during local inference: {str(e)}"
            logger.error(err_msg)
            raise AIProviderError(err_msg)

    def check_health(self) -> dict[str, Any]:
        """Check if Ollama is reachable and whether the configured model is installed."""
        endpoint = f"{self.base_url}/api/tags"
        try:
            resp = requests.get(endpoint, timeout=3)
            if resp.status_code == 200:
                models_data = resp.json().get("models", [])
                available_models = [m.get("name") for m in models_data]
                is_model_present = any(self.model_name in m for m in available_models)
                return {
                    "available": True,
                    "provider": self.provider_name,
                    "model": self.model_name,
                    "model_installed": is_model_present,
                    "installed_models": available_models,
                    "details": "Ollama local inference service connected."
                }
            return {
                "available": False,
                "provider": self.provider_name,
                "model": self.model_name,
                "details": f"Ollama returned HTTP status {resp.status_code}."
            }
        except Exception as e:
            return {
                "available": False,
                "provider": self.provider_name,
                "model": self.model_name,
                "details": f"Cannot connect to Ollama ({str(e)})."
            }
