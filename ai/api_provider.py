"""
Cloud API Provider adapter for OpenAI-compatible REST endpoints.
Allows TONY to utilize cloud-hosted LLMs (e.g. OpenAI, Groq, Together, etc.).
"""
import logging
from typing import Any
import requests
from ai.provider import AIProvider, AIProviderError

logger = logging.getLogger("tony.ai.api")


class APIProvider(AIProvider):
    """
    Adapter for cloud LLMs implementing OpenAI-compatible /chat/completions API.
    """

    def __init__(
        self,
        model_name: str = "gpt-4o-mini",
        api_key: str = "",
        base_url: str = "https://api.openai.com/v1",
        timeout: int = 45,
        system_prompt: str = ""
    ):
        super().__init__(model_name=model_name)
        self.api_key = api_key
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout
        self.system_prompt = system_prompt
        self.provider_name = "cloud (API)"

    def _build_messages(self, message: str, history: list[dict[str, str]] | None) -> list[dict[str, str]]:
        """Format conversation turns for OpenAI-compatible API."""
        messages: list[dict[str, str]] = []

        if self.system_prompt:
            messages.append({"role": "system", "content": self.system_prompt})

        if history:
            for turn in history:
                role = turn.get("role", "user")
                content = turn.get("message", "")
                if content:
                    messages.append({"role": role, "content": content})

        messages.append({"role": "user", "content": message})
        return messages

    def generate_response(self, message: str, history: list[dict[str, str]] | None = None) -> str:
        """
        Send chat prompt and history to the cloud API endpoint.

        :param message: Current user message.
        :param history: Prior conversation turns.
        :return: Response text generated by the model.
        """
        if not self.api_key:
            raise AIProviderError(
                "API_KEY is not configured. Please specify API_KEY in your .env file to use the cloud provider."
            )

        endpoint = f"{self.base_url}/chat/completions"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json"
        }
        payload = {
            "model": self.model_name,
            "messages": self._build_messages(message, history),
            "temperature": 0.7
        }

        try:
            logger.info(f"Dispatching request to cloud API ({self.model_name}) at {endpoint}")
            response = requests.post(endpoint, json=payload, headers=headers, timeout=self.timeout)

            if response.status_code == 401:
                raise AIProviderError("Authentication failed: Invalid or expired API_KEY.")
            if response.status_code == 429:
                raise AIProviderError("Rate limit exceeded on cloud API provider.")
            if response.status_code != 200:
                raise AIProviderError(
                    f"Cloud API returned error (HTTP {response.status_code}): {response.text}"
                )

            data = response.json()
            choices = data.get("choices", [])
            if not choices:
                raise AIProviderError("No response choices returned by cloud API.")

            reply = choices[0].get("message", {}).get("content", "").strip()
            if not reply:
                raise AIProviderError("Received an empty message content from cloud API.")

            return reply

        except requests.exceptions.Timeout:
            err_msg = f"Cloud API request timed out after {self.timeout}s."
            logger.error(err_msg)
            raise AIProviderError(err_msg)

        except requests.exceptions.RequestException as e:
            err_msg = f"Network connection error contacting cloud API: {str(e)}"
            logger.error(err_msg)
            raise AIProviderError(err_msg)

    def check_health(self) -> dict[str, Any]:
        """Check if cloud API key is configured."""
        if not self.api_key:
            return {
                "available": False,
                "provider": self.provider_name,
                "model": self.model_name,
                "details": "API_KEY is not set in configuration."
            }
        return {
            "available": True,
            "provider": self.provider_name,
            "model": self.model_name,
            "details": f"Cloud API configured for endpoint {self.base_url}."
        }
